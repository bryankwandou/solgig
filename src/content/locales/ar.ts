// Arabic plural: one and two are full phrases; 3-10 take the plural noun,
// 11-99 the accusative singular, and 0 or 100+ the genitive singular.
const plural = (n: number, one: string, two: string, few: string, many: string, other: string) => {
  const h = n % 100;
  if (n === 1) return one;
  if (n === 2) return two;
  if (h >= 3 && h <= 10) return `${n} ${few}`;
  if (h >= 11 && h <= 99) return `${n} ${many}`;
  return `${n} ${other}`;
};

